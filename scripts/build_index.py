"""Generate index.json, .claude-plugin/marketplace.json and the README's skill sections.

    python scripts/build_index.py            # validate, then write the generated files
    python scripts/build_index.py --check    # write nothing; exit 1 if anything is stale
    python scripts/build_index.py --remote   # also validate each external SKILL.md at its ref

Exit codes: 0 ok, 1 validation failure or stale files, 2 bad arguments.
Formats: specs/001-skills-registry/contracts/ (index-json.md, marketplace.md, scripts.md).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import skillreg
from skillreg import MARKETPLACE, REPO, Skill, SkillError

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = 1
MARKERS = {"table": ("<!-- skills:table:start -->", "<!-- skills:table:end -->"),
           "install": ("<!-- skills:install:start -->", "<!-- skills:install:end -->")}


def dump(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def render_index(skills: list[Skill]) -> str:
    return dump({
        "$comment": "Generated by scripts/build_index.py from */card.json and registry/*.json. Do not edit.",
        "schema": SCHEMA,
        "marketplace": MARKETPLACE,
        "skills": [{
            "name": s.name, "description": s.description, "origin": s.origin, "href": s.href,
            "source": {"repo": s.repo, "path": s.path, "ref": s.ref},
            "install": s.install, "zip": s.zip,
        } for s in skills],
    })


def render_marketplace(skills: list[Skill]) -> str:
    def source(s: Skill):
        if s.origin == "local":
            return f"./{s.path}"
        return {"source": "git-subdir", "url": s.repo, "path": s.path, "ref": s.ref}

    return dump({
        "name": MARKETPLACE,
        "description": "Agent skills by Nathaniel Starkman, one plugin per skill. Generated by "
                       "scripts/build_index.py; do not edit.",
        "owner": {"name": "Nathaniel Starkman", "url": "https://nstarkman.space"},
        "plugins": [{"name": s.name, "description": s.description, "source": source(s), "skills": ["./"],
                     "homepage": s.href} for s in skills],
    })


def render_table(skills: list[Skill]) -> str:
    rows = ["| Skill | For | From |", "| --- | --- | --- |"]
    for s in skills:
        link = f"{s.name}/" if s.origin == "local" else s.href
        frm = "" if s.origin == "local" else f"[{s.repo}](https://github.com/{s.repo})"
        rows.append(f"| [`{s.name}`]({link}) | {s.description} | {frm} |")
    return "\n".join(rows)


def render_install() -> str:
    return f"""**Claude Code** — add this repository as a plugin marketplace once, then install any skill by name
(skills in other repositories install from there, at the version listed):

```text
/plugin marketplace add {REPO}
/plugin install <name>@{MARKETPLACE}
```

**claude.ai** — download `<name>.zip` from the
[latest release](https://github.com/{REPO}/releases/latest) and upload it under Customize → Skills.

**By hand** — copy the skill's folder (its link in the table above) into `~/.claude/skills/`, or into
a project's `.claude/skills/` for that project only."""


def replace_section(text: str, key: str, body: str) -> str:
    start, end = MARKERS[key]
    if start not in text or end not in text:
        raise SkillError(f"README.md: markers {start} … {end} are missing")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{body}\n{end}{tail}"


def outputs(root: Path, skills: list[Skill]) -> dict[Path, str]:
    readme = (root / "README.md").read_text(encoding="utf-8")
    readme = replace_section(readme, "table", render_table(skills))
    readme = replace_section(readme, "install", render_install())
    return {
        root / "index.json": render_index(skills),
        root / ".claude-plugin" / "marketplace.json": render_marketplace(skills),
        root / "README.md": readme,
    }


def validate_remote(skills: list[Skill]) -> tuple[list[str], list[str]]:
    errors, warnings = [], []
    for s in skills:
        if s.origin != "external":
            continue
        try:
            text = skillreg.fetch_skill_md(s)
        except SkillError as e:
            errors.append(str(e))
            continue
        e2, w2 = skillreg.check_skill_md(text, s.name, f"{s.name} ({s.repo}/{s.path}/SKILL.md@{s.ref})")
        errors += e2
        warnings += w2
    return errors, warnings


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing; fail if a generated file is stale")
    ap.add_argument("--remote", action="store_true", help="also validate external SKILL.md files on GitHub")
    args = ap.parse_args(argv)

    errors, warnings, skills = skillreg.validate_offline(root)
    if args.remote and not errors:
        e2, w2 = validate_remote(skills)
        errors += e2
        warnings += w2
    for w in warnings:
        print(f"warning: {w}", file=sys.stderr)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1

    try:
        files = outputs(root, skills)
    except SkillError as e:
        print(e, file=sys.stderr)
        return 1
    stale = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        if stale:
            print("stale (run python scripts/build_index.py): "
                  + ", ".join(str(p.relative_to(root)) for p in stale), file=sys.stderr)
            return 1
        print(f"{len(skills)} skills; generated files are up to date")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(files[p], encoding="utf-8")
    print(f"{len(skills)} skills ({sum(s.origin == 'external' for s in skills)} external); wrote "
          + (", ".join(str(p.relative_to(root)) for p in stale) or "nothing (up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
